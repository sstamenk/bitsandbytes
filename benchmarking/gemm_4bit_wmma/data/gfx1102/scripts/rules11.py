def load(x):
    if x in TABLES:
        return TABLES[x]
    ns = {"T": T, "INF": INF}
    exec(open(x).read(), ns)
    return ns["RULES"]


def pick(R, M, N, K, kfix=True):
    for mx, leaves, oth in R:
        if M <= mx:
            for f, lt, den, c in leaves:
                if (f == "N" and N < lt) or (f == "K" and K < lt) or (f == "KN" and K * den < lt * N):
                    c0 = c
                    break
            else:
                c0 = oth
            break
    p = c0.split(",")
    if kfix and K % 128:
        p[5] = "1"
    return ",".join(p)
